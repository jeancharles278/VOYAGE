/**
 * Génère un jeu de points d'intérêt cohérent autour du centre-ville.
 * Les positions sont déterministes (hash du slug) : elles ne bougent pas
 * d'un rendu à l'autre et restent réalistes à l'échelle d'une ville.
 */
function hash(seed: string): () => number {
  let h = 2166136261;
  for (let i = 0; i < seed.length; i++) {
    h ^= seed.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return () => {
    h += 0x6d2b79f5;
    let t = h;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function offset(center: GeoPoint, rand: () => number, kmRadius: number): GeoPoint {
  const angle = rand() * Math.PI * 2;
  const distance = (0.35 + rand() * 0.65) * kmRadius;
  return {
    lat: +(center.lat + (distance / 111) * Math.sin(angle)).toFixed(5),
    lng: +(
      center.lng +
      (distance / (111 * Math.cos((center.lat * Math.PI) / 180))) * Math.cos(angle)
    ).toFixed(5),
  };
}

function buildPoi(
  slug: string,
  name: string,
  center: GeoPoint,
  hasBeach: boolean,
  activities: Activity[],
): PointOfInterest[] {
  const rand = hash(slug);
  const poi: PointOfInterest[] = [
    {
      id: `${slug}-center`,
      name: `Centre historique de ${name}`,
      category: "center",
      position: center,
      description: "Cœur de ville, commerces et vie nocturne.",
    },
    {
      id: `${slug}-airport`,
      name: `Aéroport de ${name}`,
      category: "airport",
      position: offset(center, rand, 14),
      description: "Aéroport international principal.",
    },
  ];

  const hotelNames = ["Grand Hôtel", "Le Belvédère", "Sun Palace Resort", "Villa Aurora"];
  hotelNames.forEach((hotelName, i) => {
    poi.push({
      id: `${slug}-hotel-${i}`,
      name: `${hotelName} ${name}`,
      category: "hotel",
      position: offset(center, rand, hasBeach ? 6 : 3),
      description: `${4 + (i % 2)} étoiles`,
    });
  });

  if (hasBeach) {
    ["Plage principale", "Crique secrète"].forEach((beachName, i) => {
      poi.push({
        id: `${slug}-beach-${i}`,
        name: `${beachName} — ${name}`,
        category: "beach",
        position: offset(center, rand, 7),
        description: i === 0 ? "Sable fin, services et location de transats." : "Petite crique à l'écart des foules.",
      });
    });
  }

  ["Table du marché", "Bistrot du port", "Trattoria centrale"].forEach((restaurant, i) => {
    poi.push({
      id: `${slug}-resto-${i}`,
      name: `${restaurant}`,
      category: "restaurant",
      position: offset(center, rand, 2.5),
      description: "Cuisine locale, réservation conseillée.",
    });
  });

  activities.slice(0, 4).forEach((activity, i) => {
    poi.push({
      id: `${slug}-activity-${i}`,
      name: activity.name,
      category: "activity",
      position: offset(center, rand, 12),
      description: activity.description,
    });
  });

  return poi;
}

